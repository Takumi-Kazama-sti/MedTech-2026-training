-- テーブルの作成

-- 検体(検査する対象)
-- id：主キー
CREATE TABLE targets (
  id INTEGER PRIMARY KEY,           -- id
  target_no INTEGER NOT NULL UNIQUE,  -- 検体のNo
  target_name VARCHAR(50)             -- 検体の名前
);

-- 画像(検体ごとに複数枚)
-- id: 主キー
-- target_id: 外部キー
-- data: 画像のデータ、1枚ごとのファイルパス
CREATE TABLE images (
  id INTEGER PRIMARY KEY,
  target_id INTEGER NOT NULL references targets(id),
  data_path VARCHAR(90)
);

-- 判定結果を表示する列挙型
CREATE TYPE result_codes AS ENUM('正常', '異常', '判定不能');

-- 判定結果（画像ごと。正常・異常・判定不能のどれか、
-- 確信度、判定に使った AI モデルのバージョン、確定した人と日時）
-- id: 主キー
-- image_id: 外部キー
CREATE TABLE results (
  id INTEGER PRIMARY KEY,
  image_id INTEGER references images(id) NOT NULL,  -- 画像ID
  result result_codes,          -- 判定結果(正常異常・判定不能)
  conf_score INTEGER,           -- 確信度(0 - 100)
  ai_version VARCHAR(50),       -- AIモデルのバージョン
  created_at timestamp,         -- 確定した日時
  created_by VARCHAR(50)        -- 確定した人
);

-- 監査ログ（誰が・いつ・何をしたか）
-- id: 主キー
CREATE TABLE user_logs (
  id INTEGER GENERATED BY DEFAULT 
  AS IDENTITY PRIMARY KEY,
  created_at timestamp,   -- 日時
  created_by VARCHAR(50), -- 操作した人
  --- ログ情報(ログ管理ツールに見えやすいように)
  log_code VARCHAR(10),   -- ログコード(ID等)
  log_level VARCHAR(10),  -- ログレベル(それぞれの環境に合わす)
  log_meg text
);
